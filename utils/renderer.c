void renderer_draw_3d_triangle(vec3_t left, vec3_t top, vec3_t right, color_t color) {
	vec3_t side_a = vec3_sub(top, left);
	vec3_t side_b = vec3_sub(right, left);
	vec3_t normal = vec3_cross(side_a, side_b);

	vertex_3d_shapes_t triangle_vertex_array[3] = {
		{left, normal, color},
		{right, normal, color},
		{top, normal, color},
	};
	renderer_draw_3d_shape_mesh(triangle_vertex_array, 3);
}

void renderer_draw_cylinder(vec3_t pos1, vec3_t pos2, float radius, color_t color) {
	vec3_t axis = vec3_sub(pos2, pos1);
	vec3_t axis_normalized = vec3_normalize(axis);

	vec3_t arbitrary = (fabsf(axis_normalized.x) < 0.9f) ? vec3(1, 0, 0) : vec3(0, 1, 0);

	vec3_t tangent = vec3_normalize(vec3_cross(axis_normalized, arbitrary));
	vec3_t bitangent = vec3_cross(axis_normalized, tangent);

	vec3_t circle_points_lower[CIRCLE_SEGMENTS];
	vec3_t circle_points_upper[CIRCLE_SEGMENTS];

	for (uint32_t i = 0; i < CIRCLE_SEGMENTS; i++) {
		float angle = (2.0f * PI * i) / CIRCLE_SEGMENTS;
		float angle_offset = (2.0f * PI * (i + 1)) / CIRCLE_SEGMENTS;

		vec3_t offset_lower = vec3_add(
			vec3_scale(tangent, cosf(angle) * radius),
			vec3_scale(bitangent, sinf(angle) * radius));
		circle_points_lower[i] = vec3_add(pos1, offset_lower);

		vec3_t offset_upper = vec3_add(
			vec3_scale(tangent, cosf(angle_offset) * radius),
			vec3_scale(bitangent, sinf(angle_offset) * radius));
		circle_points_upper[i] = vec3_add(pos2, offset_upper);
	}

	uint32_t total_vertices = CIRCLE_SEGMENTS * 6 + CIRCLE_SEGMENTS * 3 + CIRCLE_SEGMENTS * 3;
	vertex_3d_shapes_t vertices[total_vertices];

	uint32_t v = 0;

	for (uint32_t i = 0; i < CIRCLE_SEGMENTS; i++) {
		uint32_t next = (i + 1) % CIRCLE_SEGMENTS;

		vec3_t edge1 = vec3_sub(circle_points_upper[i], circle_points_lower[i]);
		vec3_t edge2 = vec3_sub(circle_points_lower[next], circle_points_lower[i]);
		vec3_t normal1 = vec3_normalize(vec3_cross(edge1, edge2));

		edge1 = vec3_sub(circle_points_upper[next], circle_points_upper[i]);
		edge2 = vec3_sub(circle_points_lower[next], circle_points_upper[i]);
		vec3_t normal2 = vec3_normalize(vec3_cross(edge1, edge2));

		vertices[v++] = (vertex_3d_shapes_t){circle_points_lower[i], normal1, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_upper[i], normal1, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_lower[next], normal1, color};

		vertices[v++] = (vertex_3d_shapes_t){circle_points_upper[i], normal2, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_upper[next], normal2, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_lower[next], normal2, color};
	}

	for (uint32_t i = 0; i < CIRCLE_SEGMENTS; i++) {
		uint32_t next = (i + 1) % CIRCLE_SEGMENTS;

		vec3_t normal = vec3_normalize(vec3_cross(
			vec3_sub(circle_points_lower[next], pos1),
			vec3_sub(circle_points_lower[i], pos1)));

		vertices[v++] = (vertex_3d_shapes_t){pos1, normal, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_lower[next], normal, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_lower[i], normal, color};
	}

	for (uint32_t i = 0; i < CIRCLE_SEGMENTS; i++) {
		uint32_t next = (i + 1) % CIRCLE_SEGMENTS;

		vec3_t normal = vec3_normalize(vec3_cross(
			vec3_sub(circle_points_upper[i], pos2),
			vec3_sub(circle_points_upper[next], pos2)));

		vertices[v++] = (vertex_3d_shapes_t){pos2, normal, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_upper[i], normal, color};
		vertices[v++] = (vertex_3d_shapes_t){circle_points_upper[next], normal, color};
	}

	renderer_draw_3d_shape_mesh(vertices, total_vertices);
}

void renderer_set_font(font_t* font) {
	current_font = font;
	current_font_texture = texture_create(&ctx, current_font->atlas_width, current_font->atlas_height, TEXTURE_FORMAT_GREY_8BIT, TEXTURE_FILTERING_LINEAR);

	//convert uint8_t image to f32
	float* float_atlas = ctx.allocator->amalloc(current_font->atlas_width * current_font->atlas_height * sizeof(float));
	for (size_t i = 0; i < current_font->atlas_width * current_font->atlas_height; i++) {
	    float_atlas[i] = (float)current_font->atlas[i] / 255.0f;
	}
	
	//texture_upload(&current_font_texture, (void*)current_font->atlas, current_font->atlas_width * current_font->atlas_height);
	texture_upload(&current_font_texture, (void*)float_atlas, current_font->atlas_width * current_font->atlas_height * sizeof(float));
	ctx.allocator->afree(float_atlas);
}

void renderer_draw_text(const char* string, vec2_t pos, color_t color) {
	if (!(initialised_renderers & RENDERER_TEXT)) {
		ERROR("RENDERER_TEXT uninitialized");
		return;
	}
	if (strlen(string) < 1) return;
	if (current_font == NULL || current_font_texture.sdl_texture == NULL) {
		ERROR("No font set for text rendering!");
		return;
	}

	int32_t x_offset = pos.x;
	int32_t y_offset = pos.y;

	for (size_t i = 0; i < strlen(string); i++) {
		glyph_t* glyph = font_get_glyph(current_font, (uint32_t)string[i]);
		if (!glyph) continue;

		if (string[i] == '\n') {
			x_offset = pos.x;
			y_offset += current_font->line_height;
			continue;
		}

		vertex_text_t* vertices = arena_allocate(&renderer_text.vertex_arena, sizeof(vertex_text_t) * 6);

		vertices[0] = (vertex_text_t){.position = vec2(x_offset + glyph->left_space, y_offset),
									  .uv = vec2(glyph->src_x / current_font->atlas_width, glyph->src_y / current_font->atlas_width),
									  .color = color};	// top-left
		vertices[1] = (vertex_text_t){.position = vec2(x_offset + glyph->left_space, y_offset + current_font->font_size),
									  .uv = vec2(glyph->src_x / current_font->atlas_width, (glyph->src_y + glyph->src_height) / current_font->atlas_width),
									  .color = color};	// bottom-left
		vertices[2] = (vertex_text_t){.position = vec2(x_offset + glyph->advance_width, y_offset + current_font->font_size),
									  .uv = vec2((glyph->src_x + glyph->src_width) / current_font->atlas_width, (glyph->src_y + glyph->src_height) / current_font->atlas_width),
									  .color = color};	// bottom-right

		vertices[3] = (vertex_text_t){.position = vec2(x_offset + glyph->left_space, y_offset),
									  .uv = vec2(glyph->src_x / current_font->atlas_width, glyph->src_y / current_font->atlas_width),
									  .color = color};	// top-left
		vertices[4] = (vertex_text_t){.position = vec2(x_offset + glyph->advance_width, y_offset + current_font->font_size),
									  .uv = vec2((glyph->src_x + glyph->src_width) / current_font->atlas_width, (glyph->src_y + glyph->src_height) / current_font->atlas_width),
									  .color = color};	// bottom-right
		vertices[5] = (vertex_text_t){.position = vec2(x_offset + glyph->advance_width, y_offset),
									  .uv = vec2((glyph->src_x + glyph->src_width) / current_font->atlas_width, glyph->src_y / current_font->atlas_width),
									  .color = color};	// top-right

		x_offset += glyph->advance_width;
	}
}
